#!/bin/bash
# Silent Dialogues of Care - 境界なき対話
# テスト実行スクリプト

# ログディレクトリの作成
mkdir -p logs

echo "========================================================"
echo "  Silent Dialogues of Care - テスト実行スクリプト"
echo "========================================================"

# 必要なパッケージがインストールされているか確認
echo "依存パッケージの確認..."
python -m pip install -r requirements.txt

# 単体テストを実行
echo -e "\n---------------------------------------------------------"
echo "テキスト読み上げモジュールのテスト..."
echo "---------------------------------------------------------"
python -m unittest tests/test_audio_output.py

echo -e "\n---------------------------------------------------------"
echo "音声キャプチャモジュールのテスト..."
echo "---------------------------------------------------------"
python -m unittest tests/test_audio_capture.py

echo -e "\n---------------------------------------------------------"
echo "音声感情認識モジュールのテスト..."
echo "---------------------------------------------------------"
python -m unittest tests/test_vocal_emotion_recognition.py

echo -e "\n---------------------------------------------------------"
echo "音声認識モジュールのテスト..."
echo "---------------------------------------------------------"
python -m unittest tests/test_speech_to_text.py

echo -e "\n---------------------------------------------------------"
echo "応答生成モジュールのテスト..."
echo "---------------------------------------------------------"
python -m unittest tests/test_empathetic_response_generator.py

# 統合テストを実行
echo -e "\n---------------------------------------------------------"
echo "統合テスト..."
echo "---------------------------------------------------------"
python -m unittest tests/test_integration.py

# 環境変数の存在を確認
if [ -f .env ]; then
    echo -e "\n---------------------------------------------------------"
    echo "テキスト読み上げデモを実行しますか？(y/n)"
    echo "---------------------------------------------------------"
    read -r response
    if [[ "$response" =~ ^([yY][eE][sS]|[yY])$ ]]; then
        python tests/test_tts_demo.py
    fi
else
    echo -e "\n警告: .envファイルが見つかりません。"
    echo "APIキーを設定するには、.envファイルを作成し、以下の内容を追加してください:"
    echo "OPENAI_API_KEY=your_key_here"
    echo "HUME_API_KEY=your_key_here"
fi

echo -e "\n========================================================"
echo "  テスト完了"
echo "========================================================"\
